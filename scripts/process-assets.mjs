import { readdir, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "assets", "ai4s");
const OUT = path.join(ROOT, "public", "images");

const SIZES = [
  { key: "full", width: 1600, quality: 80 },
  { key: "md", width: 960, quality: 76 },
  { key: "sm", width: 640, quality: 72 },
  { key: "lqip", width: 32, quality: 55 },
];

const manifest = {};

for (const group of ["g01", "g02", "g03"]) {
  const dir = path.join(SRC, group);
  const files = (await readdir(dir)).filter((f) => f.endsWith(".png")).sort();

  for (const file of files) {
    const name = file.replace(/\.png$/, "");
    const input = path.join(dir, file);
    const meta = await sharp(input).metadata();
    const outDir = path.join(OUT, group);
    await mkdir(outDir, { recursive: true });

    const entry = {
      id: name,
      group,
      width: meta.width,
      height: meta.height,
      aspect: +(meta.width / meta.height).toFixed(4),
      src: {},
    };

    for (const { key, width, quality } of SIZES) {
      const outName = `${name}.${key}.webp`;
      await sharp(input)
        .resize({ width: Math.min(width, meta.width), withoutEnlargement: true })
        .webp({ quality })
        .toFile(path.join(outDir, outName));
      entry.src[key] = `/images/${group}/${outName}`;
    }

    manifest[name] = entry;
    console.log(`  ${group}/${name}  ${meta.width}x${meta.height}`);
  }
}

const manifestPath = path.join(ROOT, "src", "lib", "assets.ts");
await mkdir(path.dirname(manifestPath), { recursive: true });
const ts =
  `// AUTO-GENERATED by scripts/process-assets.mjs — do not edit by hand.\n` +
  `export type AssetKey =\n` +
  Object.keys(manifest)
    .map((k) => `  | "${k}"`)
    .join("\n") +
  `;\n\n` +
  `export type AssetSizes = { full: string; md: string; sm: string; lqip: string };\n\n` +
  `export type Asset = {\n` +
  `  id: string;\n` +
  `  group: string;\n` +
  `  width: number;\n` +
  `  height: number;\n` +
  `  aspect: number;\n` +
  `  src: AssetSizes;\n` +
  `};\n\n` +
  `export const ASSETS: Record<AssetKey, Asset> = ${JSON.stringify(
    manifest,
    null,
    2
  )};\n`;
await writeFile(manifestPath, ts);

const total = Object.keys(manifest).length;
console.log(`\nDone. ${total} assets → src/lib/assets.ts`);
