const fs = require('fs');
const postcss = require('postcss');
const files=['products','product-detail','information','navigation','dashboard','console','community','profile','login','legal','learn-everything','showcase','editorial-shared','community-editorial'];
function recolor(raw,prop){
 const color=/#[\da-f]{3,8}\b|rgba?\([^)]*\)/gi;
 return raw.replace(color, value=>{
  let r,g,b,a=1;
  if(value[0]==='#'){let h=value.slice(1);if(h.length===3||h.length===4)h=h.split('').map(c=>c+c).join('');r=parseInt(h.slice(0,2),16);g=parseInt(h.slice(2,4),16);b=parseInt(h.slice(4,6),16);if(h.length===8)a=parseInt(h.slice(6,8),16)/255;}
  else{let nums=value.match(/[\d.]+/g).map(Number);[r,g,b]=nums;if(nums.length>3)a=nums[3];}
  if(!Number.isFinite(r+g+b))return value;
  const max=Math.max(r,g,b)/255,min=Math.min(r,g,b)/255,l=(max+min)/2,d=max-min;
  let h=0,s=d===0?0:d/(1-Math.abs(2*l-1));
  if(d){if(max===r/255)h=((g-b)/255/d)%6;else if(max===g/255)h=(b-r)/255/d+2;else h=(r-g)/255/d+4;h=(h*60+360)%360;}
  if(prop.includes('shadow'))return `rgba(22,42,48,${Math.min(a,.12)})`;
  if(prop.includes('border')||prop.includes('outline')||prop.includes('line'))return `hsla(195,16%,45%,${a===1?.3:Math.max(.14,a)})`;
  let nl,ns;
  if(prop.includes('background')||prop==='--forum-panel') {nl=l<.5?97-l*13:18;ns=l<.5?Math.min(s*100,16):22;if(s<.15)h=60;}
  else {nl=l>.5?24:l<.22?94:32;ns=Math.min(s*100,48);if(s<.15)h=200;}
  return `hsla(${h.toFixed(0)},${ns.toFixed(0)}%,${nl.toFixed(0)}%,${a})`;
 });
}
const out=postcss.root();out.append(postcss.comment({text:'Light palette for non-home pages. Generated by scripts/build-light-surfaces.cjs; dark source styles remain intact.'}));
for(const file of files){
 const root=postcss.parse(fs.readFileSync(`src/components/${file}.css`,'utf8'));
 root.walkAtRules(r=>{if(/keyframes/.test(r.name))r.remove()});
 root.walkRules(rule=>{
  rule.walkDecls(decl=>{if(!/^(color|background.*|border.*|outline.*|box-shadow|text-shadow|fill|stroke|caret-color|accent-color|color-scheme|--[\w-]+)$/.test(decl.prop))decl.remove();else if(decl.prop==='color-scheme')decl.value='light';else {let v=recolor(decl.value,decl.prop);if(v===decl.value)decl.remove();else decl.value=v;}});
  if(!rule.nodes.length){rule.remove();return;}
  rule.selectors=rule.selectors.map(s=>`:root[data-theme="light"] ${s}`);
 });
 root.walkAtRules(r=>{if(!r.nodes?.length)r.remove()});out.append(root.nodes);
}
fs.writeFileSync('src/app/light-surfaces.css',out.toString()+'\n');
