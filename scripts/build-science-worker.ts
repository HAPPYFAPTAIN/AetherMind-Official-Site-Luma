import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Bun runs the script directly; keep its small build API declaration local so
// Next's TypeScript check does not require Bun's ambient types in the client.
declare const Bun: {
  build(options: {
    entrypoints: string[];
    outdir: string;
    naming: string;
    target: "browser";
    format: "esm";
    minify: boolean;
    splitting: boolean;
    sourcemap: "none";
  }): Promise<{
    success: boolean;
    logs: unknown[];
    outputs: { path: string; kind: string; size: number }[];
  }>;
  write(path: string, contents: string): Promise<number>;
};

const project = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const result = await Bun.build({
  entrypoints: [resolve(project, "src/lib/science-worker.ts")],
  outdir: resolve(project, "public/science"),
  naming: "scene-worker-[hash].js",
  target: "browser",
  format: "esm",
  minify: true,
  splitting: false,
  sourcemap: "none",
});

if (!result.success) {
  for (const message of result.logs) console.error(message);
  throw new Error("Scientific scene worker build failed");
}

const entry = result.outputs.find((output) => output.kind === "entry-point");
if (!entry) throw new Error("Scientific scene worker build produced no entry point");
const url = `/science/${basename(entry.path)}`;
await Bun.write(
  resolve(project, "src/lib/science-worker-path.ts"),
  `// Generated by scripts/build-science-worker.ts; rebuild after worker changes.\nexport const SCIENCE_WORKER_URL = ${JSON.stringify(url)};\n`,
);
console.log(`Scientific scene worker: ${url} (${Math.round(entry.size / 1024)} KiB)`);
